/**
 * Measures the height of every lazy section (Career, Projects, Skills, Contact) for each language and each
 * viewport width, and writes `src/lib/sectionHeights.generated.ts`: the table the lazy-section placeholders use
 * so the page keeps its height (and the scroll position does not jump) while a section's code is still loading.
 *
 *   npm run build && node scripts/measure-sections.mjs
 *
 * It measures the production build (`vite preview`), with every section mounted and the web font loaded. The
 * `.screen` minimum height (one screen, landscape only) is switched off: the placeholder keeps that rule through
 * the same class, so what is stored is the height of the content alone. Run it again whenever the copy or the
 * layout of those four sections changes.
 */
import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name, fallback) => process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3) ?? fallback;

const PORT = 4799;
const MIN = 320;
const MAX = 2560;
// Every pixel on phone widths (where real devices sit at 375, 390, 393, 412, 414, 430...), every 4 px beyond.
const FINE_MAX = 520;
const FINE_STEP = 1;
const COARSE_STEP = 4;
const LANGS = ["en", "es", "pt"];
const SECTIONS = [
  ["career", "carreira"],
  ["projects", "projetos"],
  ["skills", "skills"],
  ["contact", "contato"],
];

const outDir = arg("dist", "dist");
const server = spawn(process.execPath, [resolve(root, "node_modules/vite/bin/vite.js"), "preview", "--outDir", outDir, "--port", String(PORT), "--strictPort"], { cwd: root, stdio: "ignore" });
const stop = () => server.kill();
process.on("exit", stop);

async function waitForServer() {
  for (let i = 0; i < 100; i++) {
    try {
      if ((await fetch(`http://localhost:${PORT}/`)).ok) return;
    } catch {
      /* not up yet */
    }
    await new Promise((r) => setTimeout(r, 100));
  }
  throw new Error("vite preview did not start (run `npm run build` first)");
}
await waitForServer();

const browser = await chromium.launch();
const widths = [];
for (let w = MIN; w <= FINE_MAX; w += FINE_STEP) widths.push(w);
for (let w = FINE_MAX + COARSE_STEP; w <= MAX; w += COARSE_STEP) widths.push(w);

const table = {};
for (const lang of LANGS) {
  const context = await browser.newContext({ viewport: { width: MIN, height: 900 }, reducedMotion: "reduce" });
  await context.route(/kaspersky-labs\.com/, (route) => route.abort());
  await context.addInitScript((l) => localStorage.setItem("lang", l), lang);
  const page = await context.newPage();
  await page.goto(`http://localhost:${PORT}/`, { waitUntil: "load" });
  await page.waitForFunction((ids) => ids.every((id) => document.querySelector(`#${id} h2`)), SECTIONS.map(([, id]) => id), { timeout: 20000 });
  await page.addStyleTag({ content: ".screen{min-height:0 !important}" });
  await page.evaluate(() => document.fonts.ready);

  for (const [key] of SECTIONS) (table[key] ??= {})[lang] = [];
  for (const w of widths) {
    await page.setViewportSize({ width: w, height: 900 });
    // two frames: the layout (and `useMediaQuery` based switches, like the career tabs on phones) has settled
    await page.evaluate(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))));
    const clientWidth = await page.evaluate(() => document.documentElement.clientWidth);
    if (clientWidth !== w) throw new Error(`layout width ${clientWidth} differs from the viewport width ${w} (scrollbar?)`);
    const heights = await page.evaluate((ids) => ids.map((id) => document.getElementById(id).getBoundingClientRect().height), SECTIONS.map(([, id]) => id));
    SECTIONS.forEach(([key], i) => table[key][lang].push(Math.round(heights[i])));
  }
  await context.close();
  console.log("measured", lang);
}
await browser.close();
stop();

// Compact encoding: per list, the first value and then the change from one width to the next, run-length coded
// as "delta*count" (a run of zeros, common at wide screens, costs a few bytes).
function encode(list) {
  const out = [];
  let prev = 0;
  let run = 0;
  let last = null;
  const flush = () => {
    if (last === null) return;
    out.push(run > 1 ? `${last}*${run}` : `${last}`);
  };
  for (const v of list) {
    const d = v - prev;
    prev = v;
    if (d === last) run++;
    else {
      flush();
      last = d;
      run = 1;
    }
  }
  flush();
  return out.join(",");
}

const lines = [];
for (const [key] of SECTIONS) {
  for (const lang of LANGS) lines.push(`  "${key}.${lang}": "${encode(table[key][lang])}",`);
}
const file = `// Generated by scripts/measure-sections.mjs: do not edit by hand.
// Height (px) of each lazy section's content, per language: every ${FINE_STEP}px from ${MIN}px to ${FINE_MAX}px wide, then every
// ${COARSE_STEP}px up to ${MAX}px. Each string is the first value, then the change per step, run-length coded ("d*n" = n steps of d).
export const SECTION_HEIGHT_MIN_WIDTH = ${MIN};
export const SECTION_HEIGHT_FINE_MAX = ${FINE_MAX};
export const SECTION_HEIGHT_FINE_STEP = ${FINE_STEP};
export const SECTION_HEIGHT_COARSE_STEP = ${COARSE_STEP};
export const SECTION_HEIGHT_DATA: Record<string, string> = {
${lines.join("\n")}
};
`;
const out = resolve(root, arg("out", "src/lib/sectionHeights.generated.ts"));
writeFileSync(out, file);
console.log("wrote", out, `(${file.length} bytes)`);
